const ROLES = ["value_hook", "core_feature", "social_proof", "cta"] as const;
type SlideRole = typeof ROLES[number];

function parseRole(raw: unknown, fallback: SlideRole): SlideRole {
  return ROLES.includes(raw as SlideRole) ? (raw as SlideRole) : fallback;
}

function clamp(s: unknown, max: number, fallback = ""): string {
  if (typeof s !== "string" || !s.trim()) return fallback;
  return s.trim().slice(0, max);
}

function parseSlide(raw: unknown, i: number): PackSlide {
  const r = (raw ?? {}) as Record<string, unknown>;
  const roleDefaults: SlideRole[] = ["value_hook", "core_feature", "core_feature", "core_feature", "social_proof", "cta"];
  return {
    position: i + 1,
    role: parseRole(r.role, roleDefaults[i] ?? "core_feature"),
    headline: clamp(r.headline, 40, `Slide ${i + 1}`),
    subline: clamp(r.subline, 70, ""),
    headlineAr: clamp(r.headlineAr, 40) || clamp(r.headline, 40, ""),
    sublineAr: clamp(r.sublineAr, 70) || clamp(r.subline, 70, ""),
    uiFocus: clamp(r.uiFocus, 200, "app main screen"),
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Partial-parse recovery
// When Gemini truncates the response mid-JSON (token limit), extract every
// complete slide object that was fully emitted before the cut.
// ─────────────────────────────────────────────────────────────────────────────

function recoverPartialSlides(raw: string): unknown[] {
  const slides: unknown[] = [];
  // Find every {...} block that contains a "position" key — a slide object.
  // Use a simple depth-tracking scan rather than a regex so nested braces work.
  let depth = 0;
  let start = -1;
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] === "{") {
      if (depth === 0) start = i;
      depth++;
    } else if (raw[i] === "}") {
      depth--;
      if (depth === 0 && start !== -1) {
        const chunk = raw.slice(start, i + 1);
        try {
          const obj = JSON.parse(chunk) as Record<string, unknown>;
          // Only accept objects that look like slide entries
          if (typeof obj.position === "number" && typeof obj.headline === "string") {
            slides.push(obj);
          }
        } catch { /* incomplete chunk — skip */ }
        start = -1;
      }
    }
  }
  return slides;
}

