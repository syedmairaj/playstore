export type PackSlide = {
  /** Slide position 1–6 */
  position: number;
  /** Narrative role */
  role: "value_hook" | "core_feature" | "social_proof" | "cta";
  /** Bold headline ≤40 chars — rendered large on screen */
  headline: string;
  /** Supporting sub-copy ≤70 chars — rendered smaller below headline */
  subline: string;
  /** Headline in Arabic ≤40 chars */
  headlineAr: string;
  /** Subline in Arabic ≤70 chars */
  sublineAr: string;
  /** What UI state / screen to show in the phone frame */
  uiFocus: string;
};

export type ScreenshotPackResult = {
  slides: PackSlide[];
  inferredMood: string;
};

export type GenerateScreenshotPackInput = {
  appName: string;
  category: string;
  shortDescription?: string;
  /** Optimized listing title from Tier 1 — grounding context */
  listingTitle?: string;
  /** Feature bullets from Tier 1 listing */
  features?: string;
  /**
   * Tier 1 listing intelligence — when present these OVERRIDE generic copy generation.
   * The 6 screenshot slots must be synchronized with these listing themes.
   */
  /** Screenshot captions pre-generated by the Listing Optimizer (up to 5 slots) */
  screenshotCaptions?: string[];
  /** Top-ranking keywords from the Listing Optimizer */
  keywordSuggestions?: string[];
  /** Strategic theme / positioning summary from the Listing Optimizer */
  strategySummary?: string;
  /** CTA suggestions from the Listing Optimizer */
  ctaSuggestions?: string[];
  style: string;
  brandColor?: string;
  /** User-supplied theme/mood override */
  theme?: string;
  /** User-supplied headline override — applied to slide 1 (value hook) */
  headlineOverride?: string;
  /** User-supplied subline override — applied to slide 1 */
  sublineOverride?: string;
  locale: "en" | "ar";
  optimizedForConversion: boolean;
};

