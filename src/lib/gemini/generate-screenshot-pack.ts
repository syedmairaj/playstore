export async function generateScreenshotPack(
  input: GenerateScreenshotPackInput,
): Promise<ScreenshotPackResult> {
  const inferredMood = input.theme?.trim() || inferMood(input.category);

  // ✅ REFACTORED: Use centralized Vertex AI gateway (no API key needed)
  const model = getGenerativeModel({
    maxOutputTokens: 6000,
    temperature: 0.65,
  });

  const prompt = buildPrompt(input, inferredMood);
  const result = await model.generateContent(prompt);
  const text = result.response.text().trim();

  // Strip code fences if present
  const clean = text.startsWith("```")
    ? text.replace(/^```[a-zA-Z]*\n?/, "").replace(/\n?```\s*$/, "").trim()
    : text;

  let parsed: unknown;
  try {
    parsed = JSON.parse(clean);
  } catch {
    // Partial-parse recovery: Gemini truncated the JSON mid-stream (token limit hit).
    // Extract any complete slide objects that were emitted before truncation so the
    // pipeline can continue with whatever slides are available — better than hard failure.
    const recovered = recoverPartialSlides(clean);
    if (recovered.length > 0) {
      console.warn(`[generateScreenshotPack] JSON truncated — recovered ${recovered.length}/6 slides`);
      parsed = { slides: recovered, inferredMood: inferredMood };
    } else {
      throw new InvalidModelOutputError(
        `Screenshot pack: JSON parse failed and no slides could be recovered. Raw: ${clean.slice(0, 400)}`,
      );
    }
  }

  const root = (parsed ?? {}) as Record<string, unknown>;
  const rawSlides = Array.isArray(root.slides) ? root.slides : [];

  // Ensure exactly 6 slides — pad or trim
  const slides: PackSlide[] = Array.from({ length: 6 }, (_, i) =>
    parseSlide(rawSlides[i], i),
  );

  // Apply user overrides to slide 1
  if (input.headlineOverride?.trim()) slides[0].headline = input.headlineOverride.trim().slice(0, 40);
  if (input.sublineOverride?.trim()) slides[0].subline = input.sublineOverride.trim().slice(0, 70);

  return {
    slides,
    inferredMood: clamp(root.inferredMood, 120, inferredMood),
  };
}
