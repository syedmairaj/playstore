function buildPrompt(input: GenerateScreenshotPackInput, inferredMood: string): string {
  const {
    appName, category, shortDescription, listingTitle, features,
    screenshotCaptions, keywordSuggestions, strategySummary, ctaSuggestions,
    style, brandColor, theme, headlineOverride, sublineOverride,
    locale, optimizedForConversion,
  } = input;

  const mood = theme?.trim() || inferredMood;
  const hasListingIntelligence = optimizedForConversion && (
    (screenshotCaptions && screenshotCaptions.length > 0) ||
    (keywordSuggestions && keywordSuggestions.length > 0) ||
    !!strategySummary
  );

  // ── Core app context ──────────────────────────────────────────────────────
  const contextParts: string[] = [
    `App name: "${appName}"`,
    `Category: ${category}`,
  ];
  if (listingTitle) contextParts.push(`Optimized Play Store title: "${listingTitle}"`);
  if (shortDescription) contextParts.push(`Short description: "${shortDescription}"`);
  if (features) contextParts.push(`Key features:\n${features}`);
  if (brandColor) contextParts.push(`Brand color: ${brandColor}`);
  contextParts.push(`Visual style: ${style}`);
  contextParts.push(`Visual mood: ${mood}`);

  // ── Listing intelligence block (Tier 1) ───────────────────────────────────
  // When the Listing Optimizer has generated this app's listing, these fields
  // are MANDATORY CONSTRAINTS — not suggestions. The screenshots must be
  // semantically synchronized with the listing so users see the same story
  // in the store listing AND in the screenshots.
  const listingIntelligenceParts: string[] = [];

  if (strategySummary) {
    listingIntelligenceParts.push(`Strategic positioning: "${strategySummary}"`);
  }
  if (screenshotCaptions && screenshotCaptions.length > 0) {
    listingIntelligenceParts.push(
      `Pre-optimized screenshot captions from Listing Optimizer (USE THESE as your primary copy source — adapt, do not ignore):\n` +
      screenshotCaptions.map((c, i) => `  Slot ${i + 1}: "${c}"`).join("\n"),
    );
  }
  if (keywordSuggestions && keywordSuggestions.length > 0) {
    // Top 8 keywords — enough context without overwhelming the prompt
    const topKws = keywordSuggestions.slice(0, 8).join(", ");
    listingIntelligenceParts.push(`Target keywords (weave naturally into headlines/sublines): ${topKws}`);
  }
  if (ctaSuggestions && ctaSuggestions.length > 0) {
    // ctaSuggestions[0] is the WHY THIS RANKS rationale in v6+; skip if too long
    const usableCtas = ctaSuggestions.filter(c => c.length <= 120).slice(0, 3);
    if (usableCtas.length > 0) {
      listingIntelligenceParts.push(`CTA themes from optimizer:\n` + usableCtas.map(c => `  - "${c}"`).join("\n"));
    }
  }

  const overrideNote = (headlineOverride || sublineOverride)
    ? `\nUSER OVERRIDES (apply to Slide 1 only):${headlineOverride ? `\n  - Headline: "${headlineOverride}"` : ""}${sublineOverride ? `\n  - Subline: "${sublineOverride}"` : ""}`
    : "";

  const isAr = locale === "ar";

  const listingIntelligenceSection = hasListingIntelligence
    ? `\n══════════════════════════════════════════
AI LISTING OPTIMIZER SYNC (MANDATORY CONSTRAINTS)
══════════════════════════════════════════
The following data comes from this app's AI-optimized Play Store listing.
Your 6 screenshot captions MUST be semantically synchronized with these themes.
Users will see the listing text AND these screenshots in the same store page —
they must tell a consistent, reinforcing story. No contradictions, no redundancy.

${listingIntelligenceParts.join("\n\n")}

SYNC RULES:
• Slides 1–2 must lead with the SAME value proposition as the listing title/short description.
• Keywords from the optimizer must appear naturally in at least 4 of the 6 slides.
• If pre-optimized captions are provided, use them as your primary copy source.
  Adapt for the ≤40 char headline limit — do NOT ignore them.
• The strategic theme must be the BACKBONE of the entire 6-slide narrative.`
    : "";

  return `You are the Head of ASO at a top-tier app growth studio. Your job is to write a 6-slide conversion carousel that turns browsers into installers. These assets will be seen by millions of users — every word must earn its place.

BRAND CONTEXT
-------------
${contextParts.join("\n")}
${listingIntelligenceSection}
${overrideNote}

══════════════════════════════════════════
THE BRAND MIRROR NARRATIVE ARC (MANDATORY)
══════════════════════════════════════════

You MUST follow this exact story arc. Do not deviate.

SLIDE 1 — HERO VALUE HOOK (role: "value_hook") ★ MOST IMPORTANT
  Mission: Make someone stop scrolling in 0.5 seconds.
  Formula: [Transformation or Outcome] + [Time or Ease signal]
  MANDATORY: Lead with the RESULT the user experiences, not the feature that delivers it.
  WRONG: "Advanced habit tracking system"
  RIGHT: "Build 10 habits. Break 3 bad ones. In 30 days."
  The headline must create an instant desire to know more.

SLIDE 2 — CORE BENEFIT 1 (role: "core_feature")
  Mission: Prove Slide 1's promise with the strongest specific capability.
  Formula: [Specific action] + [Concrete measurable outcome]
  Show the app doing something users desperately want. Be precise — numbers convert.

SLIDE 3 — CORE BENEFIT 2 (role: "core_feature")
  Mission: Address the second most common user pain point.
  Formula: [Pain relief] + [New possibility it unlocks]
  This slide converts the "interested but not convinced" segment.

SLIDE 4 — CORE BENEFIT 3 (role: "core_feature")
  Mission: The differentiator — what makes this app different from alternatives?
  Formula: [Unique feature] + [Why that matters to users]
  This is where you win against competitors.

SLIDE 5 — SOCIAL PROOF & TRUST (role: "social_proof")
  Mission: Remove the last objection — "can I trust this?".
  Use SPECIFIC trust signals: exact user counts, star ratings, awards, press mentions, or user outcomes.
  WRONG: "Loved by millions"
  RIGHT: "4.9★ · 2.3M installs · #1 in 14 countries"
  Make it feel like proof, not marketing.

SLIDE 6 — DOWNLOAD CTA (role: "cta")
  Mission: Close the install. Create urgency or articulate the life change.
  Formula: [What changes when you install] + [Implicit urgency or FOMO]
  WRONG: "Download now. It's free."
  RIGHT: "Your streak starts today. Don't let tomorrow be Day 1."

══════════════════════════════════════════
COPY CRAFT RULES (AGENCY STANDARD)
══════════════════════════════════════════
• headline: ≤40 characters. Every word must pull weight. Cut adjectives unless they add precision.
• subline: ≤70 characters. Completes the headline's thought. Adds specificity or emotional depth.
• BANNED PHRASES: "Easy to use", "Download now", "Try for free", "All in one", "Simple", "Powerful", "Amazing"
• REQUIRED: Concrete numbers wherever possible. "Save 2 hours/week" > "Save time".
• TONE: Confident, direct, benefit-led. Like the brand has earned the right to be bold.

══════════════════════════════════════════
${isAr ? "ARABIC COPY REQUIREMENTS (CRITICAL)" : "ARABIC COPY (headlineAr / sublineAr)"}
══════════════════════════════════════════
${isAr
  ? `PRIMARY LANGUAGE: Arabic. The Arabic copy IS the primary creative — not a translation.
• Write in natural, contemporary Arabic that resonates with Arabic-speaking users in the Gulf, Levant, and wider MENA region.
• Use concise, powerful Arabic that feels native to a premium mobile app — not formal or stiff.
• Mirror the EMOTIONAL IMPACT of the English, not the words.
• Arabic RTL typography: short, punchy lines work better than long flowing sentences.
• headlineAr ≤ 35 characters (Arabic characters are wider visually).
• sublineAr ≤ 60 characters.`
  : `• Write CULTURALLY RESONANT Arabic — NOT a word-for-word translation.
• The Arabic copy must feel like it was written by an Arabic native speaker who understands MENA app culture.
• Maintain the same emotional punch and specificity as the English.
• headlineAr ≤ 35 characters. sublineAr ≤ 60 characters.
• Use modern, accessible Arabic — not overly formal Classical Arabic.`}

══════════════════════════════════════════
UI FOCUS & INFERRED MOOD
══════════════════════════════════════════
• uiFocus: the specific app screen/state for the Android phone frame on this slide.
  Make it slide-specific and authentic to the app's function.
• inferredMood: 5–10 word visual atmosphere for the background engine.
  Examples: "deep navy geometric fintech precision", "warm amber artisan food discovery", "electric teal fitness momentum"

Return JSON matching the schema. role must be one of: "value_hook", "core_feature", "social_proof", "cta".`;
}

